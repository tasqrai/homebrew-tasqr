# Maintainer notes.
#
# Version bumps are automated. Third-party taps get no bump bot, so
# .github/workflows/update-formula.yml is ours: it watches PyPI, rebuilds this file
# against any new tasqr-mcp sdist, proves the result installs, and pushes to main.
# Publishing to PyPI from tasqr-mcp-python is the only step a human takes.
#
# To do it by hand, or to finish a run that failed: point url/sha256 at the new sdist
# (.github/scripts/bump_formula.py <version>), then
#   brew update-python-resources tasqrai/tasqr/tasqr-mcp
#   python3 .github/scripts/check_pure_python.py
#   brew audit --strict --online tasqrai/tasqr/tasqr-mcp
#   brew install --formula tasqrai/tasqr/tasqr-mcp && brew test tasqrai/tasqr/tasqr-mcp
#
# `depends_on "python@3.14"` is NOT automated. It needs a manual bump when Homebrew
# retires that formula, and nothing here will warn you first.
